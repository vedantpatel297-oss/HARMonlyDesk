    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                       
        String user = jTextField1.getText().trim();
        String pass = jTextField2.getText().trim();
        String role = jComboBox1.getSelectedItem().toString();

        if (user.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username and Password cannot be empty!", "Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false", "root", "root");
            PreparedStatement pstmt = conn.prepareStatement("INSERT INTO Users (username, password, role) VALUES (?, ?, ?)");
            pstmt.setString(1, user);
            pstmt.setString(2, pass);
            pstmt.setString(3, role);

            pstmt.executeUpdate();
            pstmt.close();
            conn.close();

            JOptionPane.showMessageDialog(this, "New user account created successfully!");
            loadTableData();
            
            jTextField1.setText("");
            jTextField2.setText("");
        } catch (Exception e) {
            // Catches duplicate username errors nicely
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
                             
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
                                        
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a user to update!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int userId = (int) jTable1.getValueAt(selectedRow, 0); // Hidden ID
        String user = jTextField1.getText().trim();
        String pass = jTextField2.getText().trim();
        String role = jComboBox1.getSelectedItem().toString();

        try {
            Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false", "root", "root");
            PreparedStatement pstmt = conn.prepareStatement("UPDATE Users SET username=?, password=?, role=? WHERE id=?");
            pstmt.setString(1, user);
            pstmt.setString(2, pass);
            pstmt.setString(3, role);
            pstmt.setInt(4, userId);

            pstmt.executeUpdate();
            pstmt.close();
            conn.close();

            JOptionPane.showMessageDialog(this, "User details updated!");
            loadTableData();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
                       
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a user to remove!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int userId = (int) jTable1.getValueAt(selectedRow, 0);
        String user = jTable1.getValueAt(selectedRow, 1).toString();
        
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to permanently delete the account for " + user + "?", "Confirm Deletion", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false", "root", "root");
                PreparedStatement pstmt = conn.prepareStatement("DELETE FROM Users WHERE id=?");
                pstmt.setInt(1, userId);
                pstmt.executeUpdate();
                pstmt.close();
                conn.close();

                JOptionPane.showMessageDialog(this, "User " + user + " has been removed.");
                loadTableData();
                jTextField1.setText("");
                jTextField2.setText("");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

