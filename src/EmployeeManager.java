    private void setupDatabase() {
        String dbUrl = "jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false";
        String dbUser = "root";
        String dbPass = "root";
        try {
            Connection conn = DriverManager.getConnection(dbUrl, dbUser, dbPass);
            Statement stmt = conn.createStatement();
            // Matches your schema perfectly
            String sql = "CREATE TABLE IF NOT EXISTS Employees ("
                    + "emp_id INT PRIMARY KEY AUTO_INCREMENT, "
                    + "name VARCHAR(100) NOT NULL, "
                    + "department VARCHAR(50) NOT NULL, "
                    + "contact VARCHAR(15) NOT NULL, "
                    + "role VARCHAR(50) NOT NULL"
                    + ")";
            stmt.executeUpdate(sql);
            stmt.close();
            conn.close();
        } catch (Exception e) {
            System.out.println("Database setup error: " + e.getMessage());
        }
    }

    private void loadTableData() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        String dbUrl = "jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false";
        String dbUser = "root";
        String dbPass = "root";
        try {
            Connection conn = DriverManager.getConnection(dbUrl, dbUser, dbPass);
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery("SELECT * FROM Employees");

            while (rs.next()) {
                int id = rs.getInt("emp_id");
                String name = rs.getString("name");
                String dept = rs.getString("department");
                String contact = rs.getString("contact");
                String role = rs.getString("role");

                model.addRow(new Object[]{id, name, dept, contact, role});
            }
            rs.close();
            stmt.close();
            conn.close();
        } catch (Exception e) {
            System.out.println("Error loading table: " + e.getMessage());
        }
    }

