    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name = jTextField1.getText().trim();
        String dept = jComboBox1.getSelectedItem().toString();
        String contact = jTextField2.getText().trim();
        String role = jTextField3.getText().trim();

        if (name.isEmpty() || contact.isEmpty() || role.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields!", "Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false", "root", "root");
            PreparedStatement pstmt = conn.prepareStatement("INSERT INTO Employees (name, department, contact, role) VALUES (?, ?, ?, ?)");
            pstmt.setString(1, name);
            pstmt.setString(2, dept);
            pstmt.setString(3, contact);
            pstmt.setString(4, role);

            pstmt.executeUpdate();
            pstmt.close();
            conn.close();

            JOptionPane.showMessageDialog(this, "Employee added successfully!");
            loadTableData();
            
            // Clear fields
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
                                      
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select an employee to update!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int empId = (int) jTable1.getValueAt(selectedRow, 0); // Hidden ID
        String name = jTextField1.getText().trim();
        String dept = jComboBox1.getSelectedItem().toString();
        String contact = jTextField2.getText().trim();
        String role = jTextField3.getText().trim();

        try {
            Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false", "root", "root");
            PreparedStatement pstmt = conn.prepareStatement("UPDATE Employees SET name=?, department=?, contact=?, role=? WHERE emp_id=?");
            pstmt.setString(1, name);
            pstmt.setString(2, dept);
            pstmt.setString(3, contact);
            pstmt.setString(4, role);
            pstmt.setInt(5, empId);

            pstmt.executeUpdate();
            pstmt.close();
            conn.close();

            JOptionPane.showMessageDialog(this, "Employee updated successfully!");
            loadTableData();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
                                  
         int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select an employee to remove!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int empId = (int) jTable1.getValueAt(selectedRow, 0);
        String name = jTable1.getValueAt(selectedRow, 1).toString();
        
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to fire " + name + "?", "Confirm Termination", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false", "root", "root");
                PreparedStatement pstmt = conn.prepareStatement("DELETE FROM Employees WHERE emp_id=?");
                pstmt.setInt(1, empId);
                pstmt.executeUpdate();
                pstmt.close();
                conn.close();

                JOptionPane.showMessageDialog(this, name + " has been removed from the system.");
                loadTableData();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

