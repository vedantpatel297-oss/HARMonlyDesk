    private void setupDatabase() {
        String dbUrl = "jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false";
        String dbUser = "root";
        String dbPass = "root";
        try {
            Connection conn = DriverManager.getConnection(dbUrl, dbUser, dbPass);
            Statement stmt = conn.createStatement();
            String sql = "CREATE TABLE IF NOT EXISTS StressLogs ("
                    + "log_id INT PRIMARY KEY AUTO_INCREMENT, "
                    + "emp_id INT NOT NULL, "
                    + "log_date DATE NOT NULL, "
                    + "stress_level INT NOT NULL, "
                    + "notes VARCHAR(255)"
                    + ")";
            stmt.executeUpdate(sql);
            stmt.close();
            conn.close();
        } catch (Exception e) {
            System.out.println("Database setup error: " + e.getMessage());
        }
    }
    private void loadTableData() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        String dbUrl = "jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false";
        String dbUser = "root";
        String dbPass = "root";
        try {
            Connection conn = DriverManager.getConnection(dbUrl, dbUser, dbPass);
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery("SELECT * FROM StressLogs");

            while (rs.next()) {
                int logId = rs.getInt("log_id");
                int empId = rs.getInt("emp_id");
                String date = rs.getString("log_date");
                int stress = rs.getInt("stress_level");
                String remarks = rs.getString("notes");

                model.addRow(new Object[]{logId, empId, date, stress, remarks});
            }
            rs.close();
            stmt.close();
            conn.close();
        } catch (Exception e) {
            System.out.println("Error loading table: " + e.getMessage());
        }
    }

