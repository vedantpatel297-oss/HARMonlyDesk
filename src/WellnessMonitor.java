    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
         int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a row from the table to delete!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int logId = (int) jTable1.getValueAt(selectedRow, 0);
        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete log ID " + logId + "?", "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            String dbUrl = "jdbc:mysql://localhost:3306/harmonelydesk?useSSL=false";
            String dbUser = "root";
            String dbPass = "root";

            try {
                Connection conn = DriverManager.getConnection(dbUrl, dbUser, dbPass);
                PreparedStatement pstmt = conn.prepareStatement("DELETE FROM StressLogs WHERE log_id = ?");
                pstmt.setInt(1, logId);
                pstmt.executeUpdate();
                pstmt.close();
                conn.close();

                JOptionPane.showMessageDialog(this, "Record deleted successfully!");
                loadTableData();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

